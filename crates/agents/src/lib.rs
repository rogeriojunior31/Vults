pub trait Agent: Send + Sync {
    fn kind(&self) -> AgentKind;
    /// Normalizes a hook event; `None` for events the app ignores.
    fn parse(&self, event: &Event) -> Option<AgentUpdate>;
    /// The file the installer edits, under the user's home.
    fn config_file(&self, home: &Path) -> PathBuf;
    /// What the installer adds to that file.
    fn hook_entries(&self, hook_exe: &Path) -> Vec<HookEntry>;
    /// A statusLine command for the same file, when the agent reports usage only there.
    fn status_line(&self, _hook_exe: &Path) -> Option<String> {
        None
    }
    /// `config` with our entries (re)installed. Most agents keep Claude Code's `hooks` object.
    fn install(&self, config: &Value, hook_exe: &Path) -> Value {
        vults_agent_config::with_ours(config, &self.hook_entries(hook_exe), MARKER)
    }
    /// Why installing into `config` would overwrite something of the user's; nothing is written then.
    fn install_blocked(&self, _config: &Value) -> Option<String> {
        None
    }
    /// `config` without our entries, and nothing else changed.
    fn uninstall(&self, config: &Value) -> Value {
        vults_agent_config::remove_ours(config, MARKER)
    }
    fn installed(&self, config: &Value) -> bool {
        vults_agent_config::has_ours(config, MARKER)
    }
    /// Our entries in `config` are exactly what [`Agent::install`] would write for `hook_exe`.
    fn up_to_date(&self, config: &Value, hook_exe: &Path) -> bool {
        vults_agent_config::ours_match(config, &self.hook_entries(hook_exe), MARKER)
    }
    /// The command of our first entry: which hook binary the config runs.
    fn our_command<'a>(&self, config: &'a Value) -> Option<&'a str> {
        vults_agent_config::our_command(config, MARKER)
    }
}

/// A built-in agent: the ones the installer knows. Other tools install their hooks themselves.
pub fn agent(kind: AgentKind) -> Option<&'static dyn Agent> {
    match kind {
        AgentKind::Claude => Some(&Claude),
        AgentKind::Codex => Some(&Codex),
        AgentKind::Gemini => Some(&Gemini),
        // Set up with a plugin file, not hooks: see [`plugin`].
        AgentKind::OpenCode | AgentKind::Other => None,
    }
}

/// An agent the installer can set up, by the name `--agent` gives it: the built-in ones, and
/// tools that go by their own name but have a config we know how to edit.
pub fn installable(name: &str) -> Option<&'static dyn Agent> {
    match name {
        antigravity::NAME => Some(&Antigravity),
        _ => agent(AgentKind::parse(name)?),
    }
}

/// An agent set up with a whole file of ours that it loads by itself (a plugin), instead of
/// entries in its config. `name` is what the plugin passes to `--agent`.
#[derive(Debug)]
pub struct PluginAgent {
    pub name: &'static str,
    /// Where the file goes, from the user's config folder (`$XDG_CONFIG_HOME` or `~/.config`).
    pub file: fn(&Path) -> PathBuf,
    /// The file, running `hook_exe`.
    pub text: fn(&Path) -> String,
}

/// A plugin agent the installer can set up, by the name its sessions arrive with.
pub fn plugin(name: &str) -> Option<&'static PluginAgent> {
    match name {
        opencode::NAME => Some(&OPENCODE),
        _ => None,
    }
}

/// The line that makes a plugin file ours: a file without it is the user's and stays untouched.
pub fn plugin_marker() -> String {
    format!("Generated by {}", vults_brand::NAME)
}

/// Normalizes a hook event from any agent; `None` for events the app ignores.
pub fn parse(event: &Event) -> Option<AgentUpdate> {
    match event.agent {
        AgentKind::Other => other::parse(event),
        AgentKind::OpenCode => opencode::parse(event),
        kind => agent(kind)?.parse(event),
    }
}

/// What the agent shows while a permission waits for a click on the island.
const WAITING: &str = "Waiting for your answer on the island";

/// Our entries are recognized by the hook binary's name in their command.
pub const MARKER: &str = vults_brand::HOOK_BIN;

/// `'<exe>' --agent <agent> <Event>`, safe for the POSIX shell the agents run hooks with
/// (Git Bash on Windows, hence forward slashes there).
pub fn hook_command(hook_exe: &Path, agent: &str, event: &str) -> String {
    let exe = hook_exe.to_string_lossy();
    let exe = if cfg!(windows) {
        exe.replace('\\', "/")
    } else {
        exe.into_owned()
    };
    format!("'{}' --agent {agent} {event}", exe.replace('\'', r"'\''"))
}

/// The hook binary a command from [`hook_command`] runs, as written there.
pub fn hook_exe_of(command: &str) -> Option<PathBuf> {
    let quoted = command.strip_prefix('\'')?;
    let end = quoted.find("' --agent ")?;
    Some(PathBuf::from(quoted[..end].replace(r"'\''", "'")))
}

/// The hook binary our entries in `config` run, when they are what `hook_exe` would get except
/// for that path (another data folder, another build). Saying "an older version" then would send
/// the user looking for an update that does not exist.
pub fn other_hook(agent: &dyn Agent, config: &Value, hook_exe: &Path) -> Option<PathBuf> {
    let exe = hook_exe_of(agent.our_command(config)?)?;
    (!agent.up_to_date(config, hook_exe) && agent.up_to_date(config, &exe)).then_some(exe)
}

/// What a step shows next to its verb, most specific field first.
const DETAIL_FIELDS: &[&str] = &[
    "command",
    "file_path",
    "path",
    "notebook_path",
    "url",
    "query",
    "pattern",
];
/// What an approval card shows: the exact thing Allow authorizes.
const TARGET_FIELDS: &[&str] = &[
    "command",
    "file_path",
    "path",
    "notebook_path",
    "url",
    "query",
    "pattern",
    "prompt",
    "description",
];

fn first_field<'a>(input: &'a serde_json::Value, fields: &[&'static str]) -> Option<(&'static str, &'a str)> {
    fields.iter().find_map(|&f| {
        let v = input.get(f)?.as_str()?.trim();
        (!v.is_empty()).then_some((f, v))
    })
}

/// `github · list_prs` for `mcp__github__list_prs`: the server and its tool.
pub(crate) fn mcp_label(tool: &str) -> Option<String> {
    let (server, name) = tool.strip_prefix("mcp__")?.split_once("__")?;
    Some(format!("{server} · {name}"))
}

/// `main.rs` for a file, the first 40 characters of a command or query.
pub(crate) fn detail(input: &serde_json::Value) -> Option<String> {
    let (field, value) = first_field(input, DETAIL_FIELDS)?;
    Some(match field {
        "file_path" | "path" | "notebook_path" => file_name(value),
        _ => shorten(value, 40),
    })
}

/// How much of the acted-on value a target keeps (its first line, at most this many characters).
const TARGET_MAX: usize = 300;

/// `Bash · rm -rf build`: the tool and the exact thing it would act on.
pub(crate) fn target(tool: &str, input: &serde_json::Value) -> String {
    match first_field(input, TARGET_FIELDS) {
        Some((_, value)) => format!("{tool} · {}", shorten(value, TARGET_MAX)),
        None => tool.to_string(),
    }
}

/// Last path component, for step details: `Editing main.rs`, not the whole path.
pub(crate) fn file_name(path: &str) -> String {
    path.trim_end_matches(['/', '\\'])
        .rsplit(['/', '\\'])
        .next()
        .unwrap_or(path)
        .to_string()
}

/// First `max` characters, on a char boundary, with an ellipsis when cut.
pub(crate) fn shorten(text: &str, max: usize) -> String {
    let text = text.trim();
    let line = text.lines().next().unwrap_or("");
    match line.char_indices().nth(max) {
        Some((i, _)) => format!("{}…", &line[..i]),
        None if line.len() < text.len() => format!("{line}…"),
        None => line.to_string(),
    }
}

/// A whole command is shown on the card when the target (one line, 300 characters) cuts it; past
/// this it would not fit the card anyway.
const MAX_FULL: usize = 2_000;

/// What a permission card shows besides the target: the agent's description of the action, the
/// whole command when the target cut it, and the lines an edit adds and removes.
pub fn ask(tool: &str, input: &Value) -> Ask {
    let text = |k: &str| input.get(k).and_then(Value::as_str);
    let full = match (tool, text("command")) {
        // A patch's command is the patch itself: its files and line counts say it better.
        ("apply_patch", _) | (_, None) => None,
        (_, Some(cmd)) => {
            let cmd = cmd.trim();
            (cmd.lines().count() > 1 || cmd.chars().count() > TARGET_MAX)
                .then(|| cmd.chars().take(MAX_FULL).collect())
        }
    };
    let (added, removed) = match tool {
        "Edit" => changed(
            text("old_string").unwrap_or_default(),
            text("new_string").unwrap_or_default(),
        ),
        "MultiEdit" => input
            .get("edits")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .map(|e| {
                let side = |k: &str| e.get(k).and_then(Value::as_str).unwrap_or_default();
                changed(side("old_string"), side("new_string"))
            })
            .fold((0, 0), |(a, r), (da, dr)| (a + da, r + dr)),
        "Write" => (count_lines(text("content").unwrap_or_default()), 0),
        "apply_patch" => patch_lines(text("command").unwrap_or_default()),
        _ => (0, 0),
    };
    // A patch's target names its files, which are never cut.
    let cut = tool != "apply_patch"
        && first_field(input, TARGET_FIELDS).is_some_and(|(_, v)| shorten(v, TARGET_MAX) != v);
    Ask {
        description: text("description").and_then(filled),
        full,
        cut,
        added,
        removed,
    }
}

fn count_lines(text: &str) -> u32 {
    text.lines().count() as u32
}

/// Lines added and removed going from `old` to `new`: what is left once the lines both share at
/// the start and at the end are set aside. Not a real diff, but right for the usual edit.
fn changed(old: &str, new: &str) -> (u32, u32) {
    let old: Vec<&str> = old.lines().collect();
    let new: Vec<&str> = new.lines().collect();
    let head = old.iter().zip(&new).take_while(|(a, b)| a == b).count();
    let tail = old[head..]
        .iter()
        .rev()
        .zip(new[head..].iter().rev())
        .take_while(|(a, b)| a == b)
        .count();
    ((new.len() - head - tail) as u32, (old.len() - head - tail) as u32)
}

/// `+` and `-` lines of a patch, leaving out its headers.
fn patch_lines(patch: &str) -> (u32, u32) {
    patch.lines().fold((0, 0), |(a, r), l| {
        if l.starts_with("+++") || l.starts_with("---") {
            (a, r)
        } else if l.starts_with('+') {
            (a + 1, r)
        } else if l.starts_with('-') {
            (a, r + 1)
        } else {
            (a, r)
        }
    })
}

/// Text an agent sent, or nothing when it sent only blanks.
pub(crate) fn filled(text: &str) -> Option<String> {
    let text = text.trim();
    (!text.is_empty()).then(|| text.to_string())
}

/// A finished card shows one line, not the reply's later paragraphs, tables or markdown.
const SUMMARY_MAX: usize = 200;

/// The first paragraph of a reply with text in it, as plain text on one line. A paragraph ends
/// at a blank line, a `---`/`***`/`___` rule or a `|` table row.
pub(crate) fn summary_line(text: &str) -> Option<String> {
    let mut paragraph = Vec::new();
    let mut title = None;
    for line in text.lines().chain([""]) {
        let t = line.trim();
        let rule = t.chars().count() >= 3 && ['-', '*', '_'].iter().any(|&c| t.chars().all(|x| x == c));
        if !(t.is_empty() || rule || t.starts_with('|')) {
            paragraph.push(t);
            continue;
        }
        let only_headings = paragraph.iter().all(|l| heading(l).is_some());
        let line = plain(paragraph.drain(..));
        if line.is_empty() {
            continue;
        }
        // `## Summary` alone says nothing; the paragraph under it does.
        if only_headings {
            title.get_or_insert(line);
            continue;
        }
        return Some(capped(line));
    }
    title.map(capped)
}

fn plain<'a>(lines: impl Iterator<Item = &'a str>) -> String {
    let mut out = String::new();
    for l in lines {
        let l = l.replace("**", "").replace("__", "").replace('`', "");
        for word in unbullet(heading(&l).unwrap_or(&l).trim()).split_whitespace() {
            if !out.is_empty() {
                out.push(' ');
            }
            out.push_str(word);
        }
    }
    out
}

fn capped(line: String) -> String {
    match line.char_indices().nth(SUMMARY_MAX) {
        Some((i, _)) => format!("{}…", line[..i].trim_end()),
        None => line,
    }
}

/// The text of a markdown heading: 1 to 6 `#` then a space or nothing. `#48`, `#!/bin/sh` and
/// `#[derive]` are text.
fn heading(line: &str) -> Option<&str> {
    let rest = line.trim_start_matches('#');
    let hashes = line.len() - rest.len();
    ((1..=6).contains(&hashes) && (rest.is_empty() || rest.starts_with(char::is_whitespace))).then_some(rest)
}

/// `- `, `* `, `• ` or `1. ` at the start of a list item.
fn unbullet(line: &str) -> &str {
    if let Some(rest) = ["- ", "* ", "• "].iter().find_map(|b| line.strip_prefix(b)) {
        return rest;
    }
    let digits = line.len() - line.trim_start_matches(|c: char| c.is_ascii_digit()).len();
    match line[digits..].strip_prefix('.') {
        Some(rest) if digits > 0 && rest.starts_with(char::is_whitespace) => rest,
        _ => line,
    }
}

