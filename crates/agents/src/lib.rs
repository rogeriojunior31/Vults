    /// A config as the user keeps it: their keys around `hooks`, every key sorted (as some tools
    /// write them), our entries running the hook from another folder. Moving them to this hook
    /// must change only the lines that name it.
    #[test]
    fn an_update_touches_only_our_lines() {
        fn sorted(v: &Value) -> Value {
            match v {
                Value::Object(m) => {
                    let mut keys: Vec<_> = m.keys().collect();
                    keys.sort();
                    Value::Object(keys.into_iter().map(|k| (k.clone(), sorted(&m[k]))).collect())
                }
                Value::Array(a) => Value::Array(a.iter().map(sorted).collect()),
                v => v.clone(),
            }
        }
        use vults_agent_config as config;
        let (old, new) = (Path::new("/old/vults-hook"), Path::new("/new/vults-hook"));
        let dir = std::env::temp_dir().join(format!("vults-agents-order-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();

        for kind in [AgentKind::Claude, AgentKind::Codex, AgentKind::Gemini] {
            let a = agent(kind).unwrap();
            let install = |v: &Value, exe: &Path| {
                let v = config::with_ours(v, &a.hook_entries(exe), MARKER);
                match a.status_line(exe) {
                    Some(c) => config::status_line::with_ours(&v, &c, MARKER),
                    None => v,
                }
            };
            let user = serde_json::json!({ "hooks": {
                "AAA": [ { "hooks": [ { "type": "command", "command": "other-tool" } ] } ],
                "zzz": [ { "hooks": [ { "type": "command", "command": "keep-me" } ] } ]
            } });
            // The user's key first, then the hooks with our events in install order.
            let mut installed =
                serde_json::json!({ "security": { "auth": { "selectedType": "oauth-personal" } } });
            for (k, v) in install(&user, old).as_object().unwrap() {
                installed[k] = v.clone();
            }

            for file in [installed.clone(), sorted(&installed)] {
                let path = dir.join(format!("{kind:?}.json"));
                std::fs::write(&path, serde_json::to_string_pretty(&file).unwrap() + "\n").unwrap();
                let plan = config::preview(&path, |v| install(v, new)).unwrap();
                let changed: Vec<&str> = plan
                    .diff
                    .lines()
                    .filter(|l| !l.starts_with("+++") && !l.starts_with("---"))
                    .filter(|l| l.starts_with('+') || l.starts_with('-'))
                    .collect();
                let ours = a.hook_entries(new).len() + usize::from(a.status_line(new).is_some());
                assert_eq!(changed.len(), 2 * ours, "{kind:?}:\n{}", plan.diff);
                for line in changed {
                    let exe = if line.starts_with('+') { "/new/" } else { "/old/" };
                    assert!(
                        line.contains("\"command\"") && line.contains(exe),
                        "{kind:?}: {line}"
                    );
                }
                // Reinstalling what is there is no change at all.
                config::apply(
                    &path,
                    &plan.fingerprint,
                    |v| install(v, new),
                    std::time::SystemTime::now(),
                )
                .unwrap();
                assert!(config::preview(&path, |v| install(v, new)).unwrap().is_noop());
            }
        }
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// The user put another tool's hook in the same group as ours, under a matcher. Update and
    /// Remove touch only our hook there; a group that holds only ours still goes on Remove.
    #[test]
    fn a_group_shared_with_another_tool_keeps_its_hook() {
        use vults_agent_config as config;
        let (old, new) = (Path::new("/old/vults-hook"), Path::new("/new/vults-hook"));
        let dir = std::env::temp_dir().join(format!("vults-agents-shared-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let theirs = serde_json::json!({ "command": "other-tool --check", "timeout": 7, "type": "command" });

        for kind in [AgentKind::Claude, AgentKind::Codex, AgentKind::Gemini] {
            let a = agent(kind).unwrap();
            let event = a.hook_entries(old)[0].event;
            let mut file = config::with_ours(&serde_json::json!({}), &a.hook_entries(old), MARKER);
            let group = &mut file["hooks"][event][0];
            group["matcher"] = "Bash".into();
            group["hooks"].as_array_mut().unwrap().insert(0, theirs.clone());
            let path = dir.join(format!("{kind:?}.json"));
            std::fs::write(&path, serde_json::to_string_pretty(&file).unwrap() + "\n").unwrap();
            let text = std::fs::read_to_string(&path).unwrap();

            // Update: only the lines naming our hook change.
            let install = |v: &Value| config::with_ours(v, &a.hook_entries(new), MARKER);
            let plan = config::preview(&path, install).unwrap();
            let changed: Vec<&str> = plan
                .diff
                .lines()
                .filter(|l| !l.starts_with("+++") && !l.starts_with("---"))
                .filter(|l| l.starts_with('+') || l.starts_with('-'))
                .collect();
            assert_eq!(
                changed.len(),
                2 * a.hook_entries(new).len(),
                "{kind:?}:\n{}",
                plan.diff
            );
            assert!(
                changed.iter().all(|l| l.contains("vults-hook")),
                "{kind:?}:\n{}",
                plan.diff
            );
            let updated = install(&file);
            assert_eq!(updated["hooks"][event][0]["matcher"], "Bash");
            assert_eq!(updated["hooks"][event][0]["hooks"][0], theirs, "{kind:?}");
            assert!(
                config::ours_match(&updated, &a.hook_entries(new), MARKER),
                "{kind:?}"
            );

            // Remove: their hook and its group stay; groups that held only ours go.
            let removed = config::remove_ours(&file, MARKER);
            let mut group = file["hooks"][event][0].clone();
            group["hooks"] = serde_json::json!([theirs]);
            assert_eq!(
                removed,
                serde_json::json!({ "hooks": { event: [group] } }),
                "{kind:?}"
            );
            let plan = config::preview(&path, |v| config::remove_ours(v, MARKER)).unwrap();
            assert!(
                plan.diff
                    .lines()
                    .filter(|l| l.starts_with('+') || l.starts_with('-'))
                    .all(|l| !l.contains("other-tool") && !l.contains("matcher")),
                "{kind:?}:\n{}",
                plan.diff
            );
            config::apply(
                &path,
                &plan.fingerprint,
                |v| config::remove_ours(v, MARKER),
                std::time::SystemTime::now(),
            )
            .unwrap();
            let after = std::fs::read_to_string(&path).unwrap();
            let theirs_text = |t: &str| -> Vec<String> {
                t.lines()
                    .filter(|l| l.contains("other-tool"))
                    .map(str::to_string)
                    .collect()
            };
            assert_eq!(theirs_text(&after), theirs_text(&text), "{kind:?}");
            assert!(!config::has_ours(&serde_json::from_str(&after).unwrap(), MARKER));
        }
        let _ = std::fs::remove_dir_all(&dir);
    }

