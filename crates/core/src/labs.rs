//! Labs: features still in beta, each off until the user turns it on in Settings → Labs. One
//! table here; `ui/src/labs.gen.ts` is its TypeScript twin (a test keeps it fresh). A feature
//! that graduates leaves the table and is on for everyone; its key in a settings file is then
//! ignored.

/// A feature in Labs.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Lab {
    /// Qwen Code as a chat engine (ACP), not yet checked with a live turn.
    AcpQwen,
    /// Copilot CLI as a chat engine (ACP), not yet checked with a live turn.
    AcpCopilot,
    /// Kimi Code as a chat engine (ACP), not yet checked with a live turn.
    AcpKimi,
}

/// One row of Settings → Labs.
#[derive(Debug)]
pub struct Entry {
    pub lab: Lab,
    /// Its key in the settings file, kebab-case; never reused for another feature.
    pub id: &'static str,
    /// What the row says, in English (the UI translates it).
    pub name: &'static str,
    pub about: &'static str,
    /// It takes effect only after Vults restarts.
    pub restart: bool,
    /// The lab it needs on first, if any.
    pub requires: Option<Lab>,
}

pub const LABS: &[Entry] = &[
    Entry {
        lab: Lab::AcpQwen,
        id: "acp-qwen",
        name: "Qwen Code in the chat",
        about: "Offer Qwen Code as an engine of Zeca's chat, through the Agent Client Protocol. It has not been checked with a live turn yet: it may ask in its own terminal or stop.",
        restart: false,
        requires: None,
    },
    Entry {
        lab: Lab::AcpCopilot,
        id: "acp-copilot",
        name: "Copilot CLI in the chat",
        about: "Offer Copilot CLI as an engine of Zeca's chat, through the Agent Client Protocol. It has not been checked with a live turn yet: a lost session may need a new conversation.",
        restart: false,
        requires: None,
    },
    Entry {
        lab: Lab::AcpKimi,
        id: "acp-kimi",
        name: "Kimi Code in the chat",
        about: "Offer Kimi Code as an engine of Zeca's chat, through the Agent Client Protocol. It has not been checked with a live turn yet: a failed turn may look finished.",
        restart: false,
        requires: None,
    },
];

impl Lab {
    pub fn entry(self) -> &'static Entry {
        LABS.iter().find(|e| e.lab == self).expect("every lab has a row")
    }

    pub fn id(self) -> &'static str {
        self.entry().id
    }

    /// The lab with this key, if it is one.
    pub fn of(id: &str) -> Option<Self> {
        LABS.iter().find(|e| e.id == id).map(|e| e.lab)
    }

    /// The lab an ACP agent of the chat waits behind (its registry key), if any.
    pub fn of_acp(key: &str) -> Option<Self> {
        match key {
            "qwen" => Some(Self::AcpQwen),
            "copilot" => Some(Self::AcpCopilot),
            "kimi" => Some(Self::AcpKimi),
            _ => None,
        }
    }
}

/// Whether `lab` is on in `chosen` (the settings' map): its own key, and the one it requires.
pub fn on(chosen: &std::collections::BTreeMap<String, bool>, lab: Lab) -> bool {
    let set = |l: Lab| chosen.get(l.id()).copied().unwrap_or(false);
    set(lab) && lab.entry().requires.is_none_or(set)
}

/// The TypeScript twin of the table, committed as `ui/src/labs.gen.ts`.
pub fn typescript() -> String {
    let mut out = String::from(
        "// Generated by `VULTS_REGEN=1 cargo test -p vults-core labs_ts`. Do not edit.\n\
         import { tk } from \"./i18n\";\n\n\
         export interface LabEntry {\n  id: string;\n  name: string;\n  about: string;\n  restart: boolean;\n  requires: string | null;\n}\n\n\
         export const LABS: readonly LabEntry[] = [\n",
    );
    for e in LABS {
        let requires = e.requires.map_or("null".to_string(), |l| format!("{:?}", l.id()));
        out += &format!(
            "  {{ id: {:?}, name: tk({:?}), about: tk({:?}), restart: {}, requires: {requires} }},\n",
            e.id, e.name, e.about, e.restart
        );
    }
    out += "];\n";
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../ui/src/labs.gen.ts");

    #[test]
    fn labs_ts_is_up_to_date() {
        let fresh = typescript();
        if std::env::var_os("VULTS_REGEN").is_some() {
            std::fs::write(PATH, &fresh).expect("write labs.gen.ts");
        }
        let committed = std::fs::read_to_string(PATH).unwrap_or_default();
        assert!(
            committed == fresh,
            "ui/src/labs.gen.ts is stale: run `VULTS_REGEN=1 cargo test -p vults-core labs_ts`"
        );
    }

    #[test]
    fn every_lab_has_one_row_and_a_key_of_its_own() {
        let mut ids: Vec<&str> = LABS.iter().map(|e| e.id).collect();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), LABS.len());
        for e in LABS {
            assert_eq!(Lab::of(e.id), Some(e.lab));
        }
    }

    #[test]
    fn a_lab_is_off_until_chosen() {
        let mut chosen = std::collections::BTreeMap::new();
        assert!(!on(&chosen, Lab::AcpKimi));
        chosen.insert("acp-kimi".to_string(), true);
        assert!(on(&chosen, Lab::AcpKimi));
        assert_eq!(Lab::of_acp("kimi"), Some(Lab::AcpKimi));
        assert_eq!(Lab::of_acp("opencode"), None, "a checked engine is not a lab");
    }
}
